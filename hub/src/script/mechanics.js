// ジャンル（システム／メカニクス）の一覧。
// 台本に mechanics: ["ワカプレ", ...] の形でタグ付けし、カタログで絞り込む。
// ボードゲームで一般的なシステムを幅広く収録。
// 主要な12システムに絞る（増やしたくなったらここに追記するだけ）。
export const MECHANICS = [
  "ワカプレ", // ワーカープレイスメント
  "デッキ構築",
  "エンジンビルド", // 拡大再生産
  "セットコレクション",
  "エリアマジョリティ", // 陣取り
  "タイル配置",
  "競り", // オークション
  "ドラフト",
  "トリックテイキング",
  "ダイス",
  "正体隠匿", // 人狼系
  "協力",
];

// マスターの並び順で、渡されたタグを並べ替える
export function sortMechanics(list) {
  return [...new Set(list)].sort(
    (a, b) => MECHANICS.indexOf(a) - MECHANICS.indexOf(b)
  );
}
